export function shuihuText(value,{prose=false}={}){
  let text=String(value||'');if(labels[text])return labels[text];
  text=text.replace(/这个月/g,'这月').replace(/接下来的/g,'此后的').replace(/接下来/g,'此后').replace(/随后/g,'当下').replace(/现在/g,'如今').replace(/已经/g,'已然').replace(/正在/g,'正自').replace(/于是/g,'当下').replace(/对方/g,'那人').replace(/朋友们/g,'众位朋友').replace(/大家/g,'众人').replace(/商量/g,'商议').replace(/了解/g,'问明').replace(/暂时/g,'暂且').replace(/先把/g,'先将').replace(/把需要/g,'将须得').replace(/需要你/g,'须得你').replace(/可以/g,'可').replace(/希望/g,'盼着').replace(/暂未/g,'尚未');
  if(prose&&text&&!/^(?:话说|且说|当下|报说|却说|此时)/.test(text))text='话说，'+text;
  return text;
}
