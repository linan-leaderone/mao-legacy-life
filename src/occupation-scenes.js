const hash=value=>{let h=2166136261;for(const character of String(value))h=Math.imul(h^character.charCodeAt(0),16777619);return h>>>0;};

export function occupationScene(kind,state={},fallback={}){
  const variants=scenes[kind];
  if(!variants)return {id:fallback.id||`personal_${kind}_routine`,title:fallback.title||'',narrative:fallback.narrative||'',diary:fallback.diary||fallback.narrative||''};
  const turn=Number.isInteger(state.turn)?state.turn:state.history?.length||0;
  // A seeded rotation changes even without a saved rhythm. Recent scene IDs
  // also cover saves made before this module existed and repeated previews.
  const ordered=[...variants].sort((a,b)=>hash(`${state.seed}:occupation:${kind}:${a[0]}`)-hash(`${state.seed}:occupation:${kind}:${b[0]}`)||a[0].localeCompare(b[0]));
  const recent=(state.lifeRhythm?.recent||[]).slice(-4).map(item=>item.eventId||item.dailyId);
  const excluded=new Set([...recent,state.current?.dailyId]);
  const start=((turn%ordered.length)+ordered.length)%ordered.length;
  const variant=Array.from({length:ordered.length},(_,i)=>ordered[(start+i)%ordered.length]).find(item=>!excluded.has(`personal_${kind}_${item[0]}`))||ordered[start];
  return {id:`personal_${kind}_${variant[0]}`,title:variant[1],narrative:variant[2],diary:variant[2]};
}
